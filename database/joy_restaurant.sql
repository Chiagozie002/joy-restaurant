--  JOY RESTAURANT — DATABASE
--  Import in phpMyAdmin (Import tab) or:  mysql -u root -p < database/joy_restaurant.sql
--  Creates the database, all tables, and sample rows so the site works immediately.
--  Default admin login:  username  admin   |  password  Joy@12345
--  !! Change that password (My Profile) and the admin email on first login. !!
-- ===========================================================================
CREATE DATABASE IF NOT EXISTS joy_restaurant CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE joy_restaurant;

-- ---------- ADMIN (one account; there is no public sign-up) ----------
CREATE TABLE IF NOT EXISTS admins (
  id            INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  username      VARCHAR(50)  NOT NULL UNIQUE,
  email         VARCHAR(150) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,              -- password_hash() output, never plain text
  full_name     VARCHAR(100) NOT NULL,
  phone         VARCHAR(30)  NOT NULL DEFAULT '',
  title         VARCHAR(100) NOT NULL DEFAULT '',   -- professional title only, not a permission
  avatar        VARCHAR(255) NULL,                  -- relative path under uploads/avatars/
  created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

-- ---------- MENU PRODUCTS (shared by homepage, e-menu and admin) ----------
CREATE TABLE IF NOT EXISTS products (
  id          INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name        VARCHAR(100) NOT NULL,
  description VARCHAR(500) NOT NULL,
  price       DECIMAL(10,2) NOT NULL,               -- Nigerian naira
  category    VARCHAR(60)  NOT NULL,                -- free text typed by the admin (no category table)
  image       VARCHAR(255) NOT NULL DEFAULT '',     -- relative path, e.g. uploads/products/abc.jpg
  available   TINYINT(1) NOT NULL DEFAULT 1,
  is_deleted  TINYINT(1) NOT NULL DEFAULT 0,        -- 1 = in Trash (soft delete)
  deleted_at  DATETIME NULL,
  created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_deleted_category (is_deleted, category)
) ENGINE=InnoDB;

-- ---------- RESERVATIONS ----------
CREATE TABLE IF NOT EXISTS reservations (
  id               INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  reference        VARCHAR(20)  NOT NULL UNIQUE,    -- generated by PHP, never by JavaScript
  name             VARCHAR(100) NOT NULL,
  email            VARCHAR(150) NOT NULL,
  phone            VARCHAR(30)  NOT NULL,
  guests           SMALLINT UNSIGNED NOT NULL,
  reservation_date DATE NOT NULL,
  reservation_time TIME NOT NULL,
  special_requests VARCHAR(500) NOT NULL DEFAULT '',
  status           ENUM('Pending','Confirmed','Cancelled') NOT NULL DEFAULT 'Pending',
  ip_address       VARCHAR(45) NOT NULL DEFAULT '',
  created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_date_time (reservation_date, reservation_time),
  INDEX idx_status (status)
) ENGINE=InnoDB;

-- ---------- CONTACT MESSAGES ----------
CREATE TABLE IF NOT EXISTS messages (
  id         INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name       VARCHAR(100) NOT NULL,
  email      VARCHAR(150) NOT NULL,
  subject    VARCHAR(150) NOT NULL,
  message    TEXT NOT NULL,
  is_read    TINYINT(1) NOT NULL DEFAULT 0,
  ip_address VARCHAR(45) NOT NULL DEFAULT '',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_read (is_read)
) ENGINE=InnoDB;

-- ---------- WEBSITE SETTINGS (key/value, edited in Admin > Website Settings) ----------
CREATE TABLE IF NOT EXISTS settings (
  setting_key   VARCHAR(60) PRIMARY KEY,
  setting_value TEXT NOT NULL,
  updated_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

-- ---------- SECURITY TABLES ----------
CREATE TABLE IF NOT EXISTS login_attempts (          -- login lockout / throttling
  id           INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  identifier   VARCHAR(150) NOT NULL,
  ip_address   VARCHAR(45)  NOT NULL,
  success      TINYINT(1) NOT NULL DEFAULT 0,
  attempted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_identifier (identifier, attempted_at),
  INDEX idx_ip (ip_address, attempted_at)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS password_resets (         -- only a SHA-256 hash of the emailed token is stored
  id         INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  admin_id   INT UNSIGNED NOT NULL,
  token_hash CHAR(64) NOT NULL UNIQUE,
  expires_at DATETIME NOT NULL,
  used_at    DATETIME NULL,
  ip_address VARCHAR(45) NOT NULL DEFAULT '',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (admin_id) REFERENCES admins(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS rate_limits (             -- throttles public forms by IP
  id         INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  bucket     VARCHAR(40) NOT NULL,
  ip_address VARCHAR(45) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_bucket_ip (bucket, ip_address, created_at)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS email_log (               -- every email attempt; failures stay here for the admin to check
  id         INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  type       VARCHAR(40)  NOT NULL,
  recipient  VARCHAR(150) NOT NULL,
  subject    VARCHAR(200) NOT NULL,
  status     ENUM('sent','failed') NOT NULL,
  error      TEXT NULL,
  reference  VARCHAR(20) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_status (status, created_at)
) ENGINE=InnoDB;

